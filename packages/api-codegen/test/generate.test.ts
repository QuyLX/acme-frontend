import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, test } from 'vitest';
import { parse } from 'yaml';
import { generate, UnsupportedOpenApiError, type OpenAPI31Document } from '../src/index';

const specText = readFileSync(join(import.meta.dirname, '../fixtures/tenants.openapi.yaml'), 'utf8');
const doc = parse(specText) as OpenAPI31Document;
const gen = () => generate(doc, { service: 'tenants', specText, specName: 'tenants.openapi.yaml' });

describe('api-codegen (AC-1, AC-2)', () => {
  test('output equals the committed golden files (regenerate with bin/api-codegen.mjs)', () => {
    for (const [name, content] of Object.entries(gen())) {
      expect(content, name).toBe(readFileSync(join(import.meta.dirname, '__generated__/tenants', name), 'utf8'));
    }
  });
  test('deterministic: same spec → byte-identical output', () => expect(gen()).toEqual(gen()));
  test('client is server-only and every file carries the GENERATED header', () => {
    const files = gen();
    expect(files['client.ts']).toMatch(/^\/\/ GENERATED[^\n]*\nimport 'server-only';/);
    for (const c of Object.values(files)) expect(c).toMatch(/^\/\/ GENERATED by @platform\/api-codegen/);
  });
  test('data classes come from x-data-class; missing → unknown (restricted)', () => {
    const dc = gen()['data-classes.ts'];
    expect(dc).toContain('"User.email": "personal"');
    expect(dc).toContain('"Problem.title": "public"');
  });
  /** Sets a value at a JSON path in a cloned spec (typed, no any). */
  const set = (d: unknown, path: string[], value: unknown) => {
    let o = d as Record<string, unknown>;
    for (const k of path.slice(0, -1)) o = o[k] as Record<string, unknown>;
    o[path.at(-1)!] = value;
  };
  const push = (d: unknown, path: string[], value: unknown) => {
    let o = d as Record<string, unknown>;
    for (const k of path) o = o[k] as Record<string, unknown>;
    (o as unknown as unknown[]).push(value);
  };
  test.each([
    ['oneOf', (d: unknown) => set(d, ['components', 'schemas', 'Tenant', 'properties', 'name'], { oneOf: [{ type: 'string' }] })],
    ['additionalProperties', (d: unknown) => set(d, ['components', 'schemas', 'Tenant', 'additionalProperties'], true)],
    ['format: ipv4', (d: unknown) => set(d, ['components', 'schemas', 'Tenant', 'properties', 'name'], { type: 'string', format: 'ipv4' })],
    ['parameter in header', (d: unknown) => push(d, ['paths', '/v1/tenants', 'get', 'parameters'], { name: 'x', in: 'header', schema: { type: 'string' } })],
    ['inline response schema', (d: unknown) => set(d, ['paths', '/v1/tenants', 'get', 'responses', '200', 'content', 'application/json', 'schema'], { type: 'object' })],
    ['openapi 3.0.3', (d: unknown) => set(d, ['openapi'], '3.0.3')],
  ])('unsupported construct "%s" fails with its name', (name, mutate) => {
    const d = structuredClone(doc);
    mutate(d);
    expect(() => generate(d, { service: 'tenants', specText, specName: 'x' })).toThrow(UnsupportedOpenApiError);
    expect(() => generate(d, { service: 'tenants', specText, specName: 'x' })).toThrow(name);
  });
});
