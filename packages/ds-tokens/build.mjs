// Builds DTCG tokens (tokens/*.json) into:
//   dist/tokens.css  — CSS variables: primitives + light semantic on :root, dark semantic on [data-theme="dark"]
//   dist/theme.css   — Tailwind v4 theme mapping semantic tokens to utilities (default palette removed)
//   dist/tokens.js / tokens.d.ts — typed constants that reference the CSS variables
//   dist/resolved.json — resolved semantic values per theme (input for the contrast check)
import { mkdirSync, writeFileSync } from 'node:fs';
import StyleDictionary from 'style-dictionary';

const PREFIX = 'ds';
const THEMES = { light: ':root', dark: '[data-theme="dark"]' };
const isSemantic = (token) => token.filePath.includes('semantic.');

mkdirSync('dist', { recursive: true });

const resolved = {};
let cssOut = '/* Generated by @platform/ds-tokens — do not edit. */\n';
let lightTokens = [];

for (const [theme, selector] of Object.entries(THEMES)) {
  const sd = new StyleDictionary({
    source: ['tokens/primitives.json', `tokens/semantic.${theme}.json`],
    log: { verbosity: 'silent' },
    platforms: {
      css: {
        transformGroup: 'css',
        prefix: PREFIX,
        buildPath: 'dist/',
        files: [
          {
            destination: `tokens.${theme}.css`,
            format: 'css/variables',
            // Light emits primitives + semantic; dark emits only the semantic overrides.
            filter: theme === 'light' ? undefined : isSemantic,
            options: { selector, outputReferences: true, showFileHeader: false },
          },
        ],
      },
    },
  });
  await sd.buildAllPlatforms();
  const { allTokens } = await sd.getPlatformTokens('css');
  resolved[theme] = Object.fromEntries(
    allTokens.filter((t) => isSemantic(t) && t.path[0] === 'color').map((t) => [t.path.slice(1).join('.'), t.$value]),
  );
  if (theme === 'light') lightTokens = allTokens;
  cssOut += (await import('node:fs')).readFileSync(`dist/tokens.${theme}.css`, 'utf8') + '\n';
}
writeFileSync('dist/tokens.css', cssOut);

// Tailwind v4 theme: utilities read the CSS variables directly (@theme inline), so switching
// data-theme at runtime restyles everything without rebuilding.
const tw = (t) => `var(--${t.name})`;
const lines = [
  '/* Generated by @platform/ds-tokens — do not edit. Requires tokens.css. */',
  '@theme inline {',
  '  --color-*: initial;',
  '  --radius-*: initial;',
  '  --shadow-*: initial;',
  '  --text-*: initial;',
  '  --font-*: initial;',
];
for (const t of lightTokens) {
  const [group, ...rest] = t.path;
  if (group === 'color' && isSemantic(t)) {
    const key = rest.filter((p, i) => !(p === 'default' && i === rest.length - 1)).join('-');
    lines.push(`  --color-${key}: ${tw(t)};`);
  } else if (group === 'radius') lines.push(`  --radius-${rest.join('-')}: ${tw(t)};`);
  else if (group === 'shadow') lines.push(`  --shadow-${rest.join('-')}: ${tw(t)};`);
  else if (group === 'font' && rest[0] === 'size') lines.push(`  --text-${rest[1]}: ${tw(t)};`);
  else if (group === 'font' && rest[0] === 'family') lines.push(`  --font-${rest[1]}: ${tw(t)};`);
  else if (group === 'font' && rest[0] === 'weight') lines.push(`  --font-weight-${rest[1]}: ${tw(t)};`);
  else if (group === 'space' && rest[0] === 'base') lines.push(`  --spacing: ${tw(t)};`);
  else if (group === 'easing') lines.push(`  --ease-${rest.join('-')}: ${tw(t)};`);
}
lines.push('  --default-font-family: var(--ds-font-family-sans);', '}', '');
writeFileSync('dist/theme.css', lines.join('\n'));

// Typed constants referencing CSS variables (theme-agnostic).
const tree = {};
for (const t of lightTokens) {
  let node = tree;
  t.path.slice(0, -1).forEach((p) => (node = node[p] ??= {}));
  node[t.path.at(-1)] = `var(--${t.name})`;
}
const json = JSON.stringify(tree, null, 2);
writeFileSync('dist/tokens.js', `// Generated by @platform/ds-tokens — do not edit.\nexport const tokens = ${json};\n`);
writeFileSync('dist/tokens.d.ts', `// Generated by @platform/ds-tokens — do not edit.\nexport declare const tokens: ${json};\n`);
writeFileSync('dist/resolved.json', `${JSON.stringify(resolved, null, 2)}\n`);
console.log(`ds-tokens: ${lightTokens.length} tokens, themes: ${Object.keys(THEMES).join(', ')}`);
